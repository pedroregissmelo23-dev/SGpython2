palavra = input("escreva uma palavra: ")
for letra in palavra :
    if letra == 'p':
        print ("p é uma letra de pedro")
    elif letra == 'e' :
        print ("e é uma letra de pedro")
    elif letra == 'd' :
        print ("d é uma letra de pedro")
    elif letra == 'r' :
        print ("r é uma letra de pedro")
    elif letra == 'o' :
        print ("o é uma letra de pedro")
    else :
        print (letra +" não é uma letra de pedro")
